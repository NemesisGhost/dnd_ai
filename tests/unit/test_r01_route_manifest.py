"""R01 S0: the route-to-command manifest is current, and its findings are pinned.

`tests/r01_route_manifest.json` is generated by `tests/r01_manifest.py` from the live route table
(`uv run python -m tests.r01_manifest` rewrites it). This is an **inventory safeguard**: it fails when a
route or command is added, moved or re-guarded, so the R01 plan's family lists cannot drift silently.
It proves source shape, not runtime order (docs/R01_FRESH_AUTHORIZATION_PLAN_2026-11-12.md section 12.5).

The two pinned sets below are S0 findings, not endorsements. They only shrink as later R01 slices land.
"""


import pytest

from dnd_ai.api.app import create_app
from tests.r01_manifest import MANIFEST_PATH, build_manifest, render

pytestmark = pytest.mark.unit

# Write routes whose only authorization is the route dependency, judged at the request's start: their
# commands take no `lock_authoring_scope` / `lock_operation_scope`, so no actor row is held and no
